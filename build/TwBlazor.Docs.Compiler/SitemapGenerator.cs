using System.Globalization;
using System.Security;
using System.Text;

namespace TwBlazor.Docs.Compiler;

/// <summary>
/// A page's route together with the date its content last changed, when known.
/// </summary>
/// <param name="Route">The page's route, e.g. <c>/card</c>.</param>
/// <param name="LastModified">The date of the last commit touching the page, or <see langword="null"/> if unknown.</param>
public sealed record PageEntry(string Route, DateOnly? LastModified);

/// <summary>
/// Generates <c>sitemap.xml</c> and the <c>PageLastModified</c> lookup class from the discovered docs pages.
/// </summary>
public static class SitemapGenerator
{
    /// <summary>
    /// The public origin of the docs site. Must match the docs project's <c>SiteMetadata.BaseUrl</c>,
    /// which builds the canonical URLs the sitemap entries have to agree with.
    /// </summary>
#pragma warning disable S1075 // The site's fixed public origin, not environment-specific
    public const string DefaultBaseUrl = "https://twblazor.com";
#pragma warning restore S1075

    /// <summary>
    /// The <c>priority</c> of the home page.
    /// </summary>
    public const string HomePriority = "1.0";

    /// <summary>
    /// The <c>priority</c> of the get started page.
    /// </summary>
    public const string GetStartedPriority = "0.8";

    /// <summary>
    /// The <c>priority</c> shared by every other page, so all components carry equal weight.
    /// </summary>
    public const string DefaultPriority = "0.5";

    private const string homeRoute = "/";
    private const string getStartedRoute = "/get-started";

    /// <summary>
    /// Builds a sitemap document listing every page with a <c>priority</c>, and a <c>lastmod</c> only for
    /// pages whose date is known.
    /// </summary>
    /// <remarks>
    /// The home and get started pages rank above every other page, which all share one priority.
    /// <c>changefreq</c> is deliberately omitted, and an inaccurate <c>lastmod</c> is worse than none, so
    /// it is only written when git supplied a real date.
    /// </remarks>
    /// <param name="entries">The pages to list.</param>
    /// <param name="baseUrl">The site origin without a trailing slash.</param>
    /// <returns>The sitemap XML text.</returns>
    public static string GenerateSitemap(IEnumerable<PageEntry> entries, string baseUrl = DefaultBaseUrl)
    {
        var origin = baseUrl.TrimEnd('/');
        var sb = new StringBuilder();

        sb.Append("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n");
        sb.Append("<urlset xmlns=\"http://www.sitemaps.org/schemas/sitemap/0.9\">\n");

        foreach (var entry in entries)
        {
            sb.Append("  <url>\n");
            sb.Append("    <loc>").Append(SecurityElement.Escape(origin + entry.Route)).Append("</loc>\n");

            if (entry.LastModified is { } date)
            {
                sb.Append("    <lastmod>").Append(date.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture)).Append("</lastmod>\n");
            }

            sb.Append("    <priority>").Append(GetPriority(entry.Route)).Append("</priority>\n");
            sb.Append("  </url>\n");
        }

        sb.Append("</urlset>\n");
        return sb.ToString();
    }

    private static string GetPriority(string route) => route switch
    {
        homeRoute => HomePriority,
        getStartedRoute => GetStartedPriority,
        _ => DefaultPriority
    };

    /// <summary>
    /// Generates the <c>PageLastModified</c> class the docs pages read to show a "last updated" date.
    /// Pages with no known date are omitted, so the lookup simply reports "unknown" for them.
    /// </summary>
    /// <param name="entries">The pages to include.</param>
    /// <returns>The C# source text.</returns>
    public static string GeneratePageLastModifiedClass(IEnumerable<PageEntry> entries)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("// This file is automatically generated by TwBlazor.Docs.Compiler");
        sb.AppendLine("// Do not edit this file manually as your changes will be overwritten");
        sb.AppendLine();
        sb.AppendLine("namespace TwBlazor.Docs.Generated;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Auto-generated last-modified dates for the docs pages, taken from git history");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static class PageLastModified");
        sb.AppendLine("{");
        sb.AppendLine("    private static readonly Dictionary<string, DateOnly> _dates = new(StringComparer.Ordinal)");
        sb.AppendLine("    {");

        foreach (var entry in entries.Where(static e => e.LastModified is not null).OrderBy(static e => e.Route, StringComparer.Ordinal))
        {
            var date = entry.LastModified!.Value;
            sb.AppendLine($"        [\"{entry.Route}\"] = new DateOnly({date.Year}, {date.Month}, {date.Day}),");
        }

        sb.AppendLine("    };");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// Looks up the date a page's content last changed.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    /// <param name=\"route\">The page's route, e.g. <c>/card</c>.</param>");
        sb.AppendLine("    /// <param name=\"date\">The date, when known.</param>");
        sb.AppendLine("    /// <returns><see langword=\"true\"/> when a date is known for the route.</returns>");
        sb.AppendLine("    public static bool TryGet(string route, out DateOnly date) => _dates.TryGetValue(route, out date);");
        sb.AppendLine("}");

        return sb.ToString();
    }
}
