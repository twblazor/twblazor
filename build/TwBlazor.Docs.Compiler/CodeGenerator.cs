using System.Text;

namespace TwBlazor.Docs.Compiler;

/// <summary>
/// Generates C# code for the CodeExamples class
/// </summary>
public static class CodeGenerator
{
    /// <summary>
    /// Generates the CodeExamples class from &lt;CodeExample&gt; and
    /// "#region CodeExample" snippets extracted directly out of the docs pages.
    /// </summary>
    public static string GenerateCodeExamplesClass(Dictionary<string, string> examples)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("// This file is automatically generated by TwBlazor.Docs.Compiler");
        sb.AppendLine("// Do not edit this file manually as your changes will be overwritten");
        sb.AppendLine();
        sb.AppendLine("namespace TwBlazor.Docs.Generated;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Auto-generated code samples extracted from CodeExample blocks in the docs pages");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static class CodeExamples");
        sb.AppendLine("{");
        sb.AppendLine("    private static readonly Dictionary<string, string> _examples = new()");
        sb.AppendLine("    {");

        foreach (var kvp in examples.OrderBy(e => e.Key, StringComparer.Ordinal))
        {
            sb.AppendLine($"        [\"{kvp.Key}\"] = @\"{EscapeString(kvp.Value)}\",");
        }

        sb.AppendLine("    };");
        sb.AppendLine();
        sb.AppendLine("    public static string Get(string name) =>");
        sb.AppendLine("        _examples.TryGetValue(name, out var value) ? value : $\"// CodeExample '{name}' not found\";");
        sb.AppendLine("}");

        return sb.ToString();
    }

    /// <summary>
    /// Generates the <c>ThemeTemplateData</c> class: <c>Theme.cs</c> split into its recombinable pieces plus
    /// each component's required theme types, as plain strings the docs' theme builder turns into its own model.
    /// </summary>
    /// <param name="template">The split <c>Theme.cs</c>.</param>
    /// <param name="componentThemes">Each component name mapped to the theme types it needs.</param>
    public static string GenerateThemeTemplateClass(ThemeTemplate template, IReadOnlyDictionary<string, List<string>> componentThemes)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("// This file is automatically generated by TwBlazor.Docs.Compiler");
        sb.AppendLine("// Do not edit this file manually as your changes will be overwritten");
        sb.AppendLine();
        sb.AppendLine("namespace TwBlazor.Docs.Generated;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Auto-generated split of the default Theme.cs and the component theme dependency map");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("internal static class ThemeTemplateData");
        sb.AppendLine("{");
        sb.AppendLine($"    public static readonly string[] Usings = [{string.Join(", ", template.Usings.Select(Literal))}];");
        sb.AppendLine();
        sb.AppendLine("    public static readonly (string Name, string Text)[] Statements =");
        sb.AppendLine("    [");
        foreach (var statement in template.Statements)
            sb.AppendLine($"        ({Literal(statement.Name)}, {Literal(statement.Text)}),");
        sb.AppendLine("    ];");
        sb.AppendLine();
        sb.AppendLine($"    public const string ReturnPrefix = {Literal(template.ReturnPrefix)};");
        sb.AppendLine();
        sb.AppendLine("    public static readonly (string TypeName, string Text)[] Blocks =");
        sb.AppendLine("    [");
        foreach (var block in template.Blocks)
            sb.AppendLine($"        ({Literal(block.TypeName)}, {Literal(block.Text)}),");
        sb.AppendLine("    ];");
        sb.AppendLine();
        sb.AppendLine($"    public const string ReturnSuffix = {Literal(template.ReturnSuffix)};");
        sb.AppendLine();
        sb.AppendLine("    public static readonly (string Component, string[] Themes)[] ComponentThemes =");
        sb.AppendLine("    [");
        foreach (var kvp in componentThemes.OrderBy(c => c.Key, StringComparer.Ordinal))
            sb.AppendLine($"        ({Literal(kvp.Key)}, [{string.Join(", ", kvp.Value.Select(Literal))}]),");
        sb.AppendLine("    ];");
        sb.AppendLine("}");

        return sb.ToString();
    }

    private static string Literal(string value) => $"@\"{EscapeString(value)}\"";

    private static string EscapeString(string str)
    {
        return str.Replace("\"", "\"\"");
    }
}
