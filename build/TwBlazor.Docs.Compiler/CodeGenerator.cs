using System.Text;

namespace TwBlazor.Docs.Compiler;

/// <summary>
/// Generates C# code for the CodeExamples class
/// </summary>
public static class CodeGenerator
{
    /// <summary>
    /// Generates the CodeExamples class from &lt;CodeExample&gt; and
    /// "#region CodeExample" snippets extracted directly out of the docs pages.
    /// </summary>
    public static string GenerateCodeExamplesClass(Dictionary<string, string> examples)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("// This file is automatically generated by TwBlazor.Docs.Compiler");
        sb.AppendLine("// Do not edit this file manually as your changes will be overwritten");
        sb.AppendLine();
        sb.AppendLine("namespace TwBlazor.Docs.Generated;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Auto-generated code samples extracted from CodeExample blocks in the docs pages");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static class CodeExamples");
        sb.AppendLine("{");
        sb.AppendLine("    private static readonly Dictionary<string, string> _examples = new()");
        sb.AppendLine("    {");

        foreach (var kvp in examples.OrderBy(e => e.Key, StringComparer.Ordinal))
        {
            sb.AppendLine($"        [\"{kvp.Key}\"] = @\"{EscapeString(kvp.Value)}\",");
        }

        sb.AppendLine("    };");
        sb.AppendLine();
        sb.AppendLine("    public static string Get(string name) =>");
        sb.AppendLine("        _examples.TryGetValue(name, out var value) ? value : $\"// CodeExample '{name}' not found\";");
        sb.AppendLine("}");

        return sb.ToString();
    }

    /// <summary>
    /// Generates the <c>ThemeTemplateData</c> class: <c>Theme.cs</c> split into its recombinable pieces plus
    /// each component's required theme types, as plain strings the docs' theme builder turns into its own model.
    /// </summary>
    /// <param name="template">The split <c>Theme.cs</c>.</param>
    /// <param name="componentThemes">Each component name mapped to the theme types it needs.</param>
    public static string GenerateThemeTemplateClass(ThemeTemplate template, IReadOnlyDictionary<string, List<string>> componentThemes)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("// This file is automatically generated by TwBlazor.Docs.Compiler");
        sb.AppendLine("// Do not edit this file manually as your changes will be overwritten");
        sb.AppendLine();
        sb.AppendLine("namespace TwBlazor.Docs.Generated;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Auto-generated split of the default Theme.cs and the component theme dependency map");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("internal static class ThemeTemplateData");
        sb.AppendLine("{");
        sb.AppendLine($"    public static readonly string[] Usings = [{string.Join(", ", template.Usings.Select(Literal))}];");
        sb.AppendLine();
        AppendArray(
            sb,
            "(string Name, string Text)[] Statements",
            template.Statements.Select(s => $"({Literal(s.Name)}, {Literal(s.Text)})"));
        sb.AppendLine();

        sb.AppendLine($"    public const string ReturnPrefix = {Literal(template.ReturnPrefix)};");
        sb.AppendLine();

        AppendArray(
            sb,
            "(string TypeName, string Text)[] Blocks",
            template.Blocks.Select(b => $"({Literal(b.TypeName)}, {Literal(b.Text)})"));
        sb.AppendLine();

        sb.AppendLine($"    public const string ReturnSuffix = {Literal(template.ReturnSuffix)};");
        sb.AppendLine();

        AppendArray(
            sb,
            "(string Component, string[] Themes)[] ComponentThemes",
            componentThemes
                .OrderBy(c => c.Key, StringComparer.Ordinal)
                .Select(c => $"({Literal(c.Key)}, [{string.Join(", ", c.Value.Select(Literal))}])"));

        sb.AppendLine("}");

        return sb.ToString();
    }

    /// <summary>
    /// Appends a <c>public static readonly</c> collection-expression array with one element per line.
    /// </summary>
    /// <param name="sb">The builder to append to.</param>
    /// <param name="declaration">The array's type and name, e.g. <c>(string A, string B)[] Items</c>.</param>
    /// <param name="elements">The already-formatted C# source for each element.</param>
    /// <summary>
    /// Generates the <c>AgentSkills</c> class the AI Agents and Skills page lists its downloads from, so the page
    /// always names the skills the build actually produced.
    /// </summary>
    /// <param name="skills">The generated skills.</param>
    public static string GenerateAgentSkillsClass(IEnumerable<AgentSkill> skills)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("// This file is automatically generated by TwBlazor.Docs.Compiler");
        sb.AppendLine("// Do not edit this file manually as your changes will be overwritten");
        sb.AppendLine();
        sb.AppendLine("namespace TwBlazor.Docs.Generated;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Auto-generated list of the agent skills published under /skills");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static class AgentSkills");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// The name of the zip holding every skill.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine($"    public const string BundleName = {Literal(LlmsGenerator.SkillsBundleName)};");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// Each skill's name, description and number of bundled reference pages, in name order.");
        sb.AppendLine("    /// </summary>");
        AppendArray(sb, "(string Name, string Description, int ReferenceCount)[] All", skills.Select(s =>
            $"({Literal(s.Name)}, {Literal(s.Description)}, {s.Files.Keys.Count(k => k.StartsWith("references/", StringComparison.Ordinal))})"));
        sb.AppendLine("}");

        return sb.ToString();
    }

    private static void AppendArray(StringBuilder sb, string declaration, IEnumerable<string> elements)
    {
        sb.AppendLine($"    public static readonly {declaration} =");
        sb.AppendLine("    [");

        foreach (var element in elements)
        {
            sb.AppendLine($"        {element},");
        }

        sb.AppendLine("    ];");
    }

    private static string Literal(string value) => $"@\"{EscapeString(value)}\"";

    private static string EscapeString(string str)
    {
        return str.Replace("\"", "\"\"");
    }
}
