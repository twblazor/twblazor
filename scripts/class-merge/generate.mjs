// --- Parity tests ----------------------------------------------------------------------------------------------

let caseCount = 0;
let theories = '';

for (const [name, inputs] of Object.entries(corpus)) {
    const cases = [...new Set(inputs)].filter(input => !knownDifferences.includes(input));
    caseCount += cases.length;

    theories += '\n    [Theory]\n';
    theories += cases.map(input => `    [InlineData(${quote(input)}, ${quote(twMerge(input))})]\n`).join('');
    theories += `    public void ${name}(string input, string expected)\n    {\n        Assert.Equal(expected, _merger.Merge(input));\n    }\n`;
}

