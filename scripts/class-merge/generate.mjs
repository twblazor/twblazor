// Generates, from the tailwind-merge npm package pinned in package.json:
//
//   src/TwBlazor/Utilities/ClassMerge/TwClassGroups.Data.cs
//       The class groups, conflicts and order sensitive modifiers of tailwind-merge's default config.
//
//   tests/TwBlazor.Tests/Utilities/ClassMerge/TwClassMergerParityTests.cs
//       One test case per input in corpus.mjs, expecting exactly what twMerge returns for it.
//
// Usage (from this folder): npm install, then npm run generate.
// To move to a newer tailwind-merge, change its version in package.json and run both again.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { getDefaultConfig, twMerge, validators } from 'tailwind-merge';
import { corpus, knownDifferences } from './corpus.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..', '..');
const version = JSON.parse(readFileSync(resolve(here, 'node_modules/tailwind-merge/package.json'), 'utf8')).version;

const quote = text => '"' + text.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\t/g, '\\t') + '"';
const write = (path, content) => writeFileSync(resolve(repoRoot, path), content.replace(/\n/g, '\r\n'));

// --- Class groups --------------------------------------------------------------------------------------------

const config = getDefaultConfig();
const validatorNames = new Map(Object.entries(validators).map(([name, validator]) => [validator, name.replace(/^is/, '')]));
const definitions = [];

// Mirrors processClassesRecursively in tailwind-merge's class-group-utils.ts, recording each definition
// against the dash separated path it is registered under instead of building the lookup tree.
function walk(group, path, classDefinitions) {
    for (const definition of classDefinitions) {
        if (typeof definition === 'string') {
            definitions.push({ group, path: [path, definition].filter(part => part !== '').join('-'), validator: null });
        } else if (typeof definition === 'function') {
            if (definition.isThemeGetter) {
                walk(group, path, definition(config.theme));
            } else if (validatorNames.has(definition)) {
                definitions.push({ group, path, validator: validatorNames.get(definition) });
            } else {
                throw new Error(`Class group "${group}" uses a validator this script does not know: ${definition}`);
            }
        } else {
            for (const [key, value] of Object.entries(definition)) {
                walk(group, [path, key].filter(part => part !== '').join('-'), value);
            }
        }
    }
}

for (const [group, classDefinitions] of Object.entries(config.classGroups)) {
    walk(group, '', classDefinitions);
}

const stringList = values => `[${values.map(quote).join(', ')}]`;
const dictionary = map => Object.entries(map).map(([key, values]) => `            [${quote(key)}] = ${stringList(values)},`).join('\n');

