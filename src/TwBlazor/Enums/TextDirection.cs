namespace TwBlazor.Enums;

/// <summary>
/// Represents the direction text and layout flow in.
/// </summary>
public enum TextDirection
{
    /// <summary>
    /// Text starts on the left and flows to the right, as in English.
    /// </summary>
    LeftToRight,

    /// <summary>
    /// Text starts on the right and flows to the left, as in Arabic, Hebrew, Persian and Urdu.
    /// </summary>
    RightToLeft
}
