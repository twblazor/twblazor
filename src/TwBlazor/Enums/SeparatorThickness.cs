namespace TwBlazor.Enums;

/// <summary>
/// Defines how thick the line of a <see cref="TwBlazor.Components.TwSeparator"/> is.
/// </summary>
public enum SeparatorThickness
{
    /// <summary>
    /// A hairline, 1px in the default theme. The default.
    /// </summary>
    Thin,

    /// <summary>
    /// A medium line, 2px in the default theme.
    /// </summary>
    Medium,

    /// <summary>
    /// A thick line, 4px in the default theme.
    /// </summary>
    Thick
}
