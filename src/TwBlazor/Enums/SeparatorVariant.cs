namespace TwBlazor.Enums;

/// <summary>
/// Defines the line style of a <see cref="TwBlazor.Components.TwSeparator"/>.
/// </summary>
public enum SeparatorVariant
{
    /// <summary>
    /// A continuous line. The default.
    /// </summary>
    Solid,

    /// <summary>
    /// A line of short dashes.
    /// </summary>
    Dashed,

    /// <summary>
    /// A line of dots.
    /// </summary>
    Dotted
}
