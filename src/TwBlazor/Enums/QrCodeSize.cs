namespace TwBlazor.Enums;

/// <summary>
/// Defines the QR code size variants.
/// </summary>
public enum QrCodeSize
{
    /// <summary>
    /// Small QR code (24x24).
    /// </summary>
    Small,

    /// <summary>
    /// Medium QR code (40x40) - Default.
    /// </summary>
    Medium,

    /// <summary>
    /// Large QR code (56x56).
    /// </summary>
    Large,

    /// <summary>
    /// Extra large QR code (72x72).
    /// </summary>
    ExtraLarge
}
