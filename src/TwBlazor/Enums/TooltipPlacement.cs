namespace TwBlazor.Enums;

/// <summary>
/// Defines which side of its content a <see cref="TwBlazor.Components.TwTooltip"/> bubble appears on.
/// </summary>
public enum TooltipPlacement
{
    /// <summary>
    /// Above the content - Default.
    /// </summary>
    Top,

    /// <summary>
    /// Below the content.
    /// </summary>
    Bottom,

    /// <summary>
    /// To the left of the content.
    /// </summary>
    Left,

    /// <summary>
    /// To the right of the content.
    /// </summary>
    Right
}
